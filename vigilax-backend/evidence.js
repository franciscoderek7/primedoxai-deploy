// ── Law enforcement format ────────────────────────────────────────────────────

function generateLEReport(pkg) {
  const linesep = '═'.repeat(70);
  const sep     = '─'.repeat(70);
  const lines = [
    linesep,
    `VIGILAX SENTINEL — FRAUD INVESTIGATION REPORT`,
    `Francisco Holdings Inc. | Authorized Disclosure`,
    linesep,
    ``,
    `DOCUMENT CLASS:    OFFICIAL INVESTIGATION REPORT`,
    `PACKAGE ID:        ${pkg.package_id}`,
    `GENERATED:         ${pkg.generated_at}`,
    `INTEGRITY HASH:    ${pkg.chain_of_custody.evidence_integrity_hash}`,
    `JURISDICTION:      ${pkg.case_information.jurisdiction}`,
    ``,
    sep,
    `SECTION 1 — FRAUD ASSESSMENT`,
    sep,
    `Engine:            ${pkg.fraud_summary.engine?.toUpperCase()}`,
    `Verdict:           ${pkg.fraud_summary.verdict}`,
    `Risk Score:        ${pkg.fraud_summary.risk_score} / 100`,
    `Severity:          ${pkg.fraud_summary.severity}`,
    `Total Findings:    ${pkg.fraud_summary.total_findings}`,
    `Critical:          ${pkg.fraud_summary.critical_findings}`,
    `High:              ${pkg.fraud_summary.high_findings}`,
    ``,
    `Recommended Action:`,
    `  ${pkg.fraud_summary.recommended_action}`,
    ``,
    sep,
    `SECTION 2 — CASE INFORMATION`,
    sep,
    `Case ID:           ${pkg.case_information.case_id}`,
    `Investigator:      ${pkg.case_information.investigator}`,
    `Client:            ${pkg.case_information.client_name || 'CONFIDENTIAL'}`,
    pkg.case_information.notes ? `Notes:             ${pkg.case_information.notes}` : null,
    ``,
    sep,
    `SECTION 3 — CHAIN OF CUSTODY`,
    sep,
    ...pkg.chain_of_custody.chain.map(s =>
      `Step ${s.step}: ${s.action}\n  Actor: ${s.actor}\n  Time:  ${s.timestamp}\n  Hash:  ${s.hash}`
    ),
    ``,
    sep,
    `SECTION 4 — FINDINGS`,
    sep,
    ...pkg.findings.map(f =>
      `[${f.finding_number}] ${f.severity} — ${f.type}\n  ${f.description || ''}\n  Affected: ${f.affected_count || '—'} records`
    ),
    ``,
    sep,
    `SECTION 5 — APPLICABLE LAW`,
    sep,
    ...(pkg.regulatory_context.relevant_laws || []).map(l => `  • ${l}`),
    ``,
    sep,
    `SECTION 6 — REPORTING AUTHORITIES`,
    sep,
    ...(pkg.regulatory_context.reporting_bodies || []).map(b => `  • ${b}`),
    ``,
    linesep,
    `END OF REPORT`,
    ``,
    `This report was generated by VIGILAX automated analysis software.`,
    `All findings must be independently verified before use in legal proceedings.`,
    linesep,
  ].filter(l => l !== null);

  return lines.join('\n');
}

