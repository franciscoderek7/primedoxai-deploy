/**
 * VIGILAX — Evidence Package Generator
 * Produces structured evidence packages for regulatory filing, law enforcement, and legal action.
 * Output: JSON manifest + HTML report (chain of custody compliant).
 */

'use strict';

const crypto = require('crypto');

// ── Chain of custody hash ────────────────────────────────────────────────────

function hashEvidence(data) {
  return crypto.createHash('sha256').update(JSON.stringify(data)).digest('hex');
}

// ── Evidence package builder ─────────────────────────────────────────────────

/**
 * buildEvidencePackage(scanResult, metadata)
 * scanResult: output from any fraud engine (click, review, influencer, ad, gov)
 * metadata: { case_id, investigator, client_name, client_contact, notes }
 */
function buildEvidencePackage(scanResult, metadata = {}) {
  const packageId = `VX-${Date.now()}-${Math.random().toString(36).slice(2, 8).toUpperCase()}`;
  const generatedAt = new Date().toISOString();
  const evidenceHash = hashEvidence(scanResult);

  const pkg = {
    package_id: packageId,
    generated_at: generatedAt,
    evidence_hash: evidenceHash,  // SHA-256 of raw scan data
    schema_version: '2.0',

    chain_of_custody: {
      collector: 'VIGILAX Sentinel Automated System',
      collection_method: 'Automated algorithmic analysis',
      collection_timestamp: generatedAt,
      hash_algorithm: 'SHA-256',
      evidence_integrity_hash: evidenceHash,
      chain: [
        {
          step: 1,
          action: 'Data collection',
          actor: 'VIGILAX Engine',
          timestamp: scanResult.analyzed_at || generatedAt,
          hash: evidenceHash,
        },
        {
          step: 2,
          action: 'Evidence package generated',
          actor: metadata.investigator || 'VIGILAX Automated',
          timestamp: generatedAt,
          hash: hashEvidence({ packageId, evidenceHash, generatedAt }),
        },
      ],
    },

    case_information: {
      case_id: metadata.case_id || packageId,
      investigator: metadata.investigator || 'Francisco Holdings Inc.',
      client_name: metadata.client_name || null,
      client_contact: metadata.client_contact || null,
      jurisdiction: metadata.jurisdiction || 'Ontario, Canada',
      notes: metadata.notes || null,
    },

    fraud_summary: {
      engine: scanResult.engine,
      verdict: scanResult.verdict,
      risk_score: scanResult.risk_score,
      severity: scanResult.severity,
      analyzed_at: scanResult.analyzed_at,
      total_findings: (scanResult.findings || []).length,
      critical_findings: (scanResult.findings || []).filter(f => f.severity === 'CRITICAL').length,
      high_findings: (scanResult.findings || []).filter(f => f.severity === 'HIGH').length,
      recommended_action: scanResult.recommended_action,
    },

    findings: (scanResult.findings || []).map((f, i) => ({
      finding_number: i + 1,
      ...f,
      evidence_items: (f.evidence ? (Array.isArray(f.evidence) ? f.evidence : [f.evidence]) : []).length,
    })),

    raw_evidence: scanResult,

    regulatory_context: getRegulatoryContext(scanResult.engine, metadata.jurisdiction),

    disclaimer: 'This evidence package is generated by VIGILAX automated analysis software. It is intended to assist investigators and legal counsel. All findings should be independently verified by qualified professionals before use in legal proceedings. Francisco Holdings Inc. makes no representations regarding the admissibility of automated evidence in any jurisdiction.',
  };

  return pkg;
}

